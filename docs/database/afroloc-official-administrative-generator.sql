create function public.afroloc_admin_nom(p_cc text,p_city text,p_neighborhood text,p_lat double precision,p_lng double precision)
returns text language plpgsql stable set search_path=public as $$
declare base text; matched record; matches integer;
begin
 base:=public.afroloc_nom(p_cc,null,null,null,p_lat,p_lng);
 if base is null or upper(p_cc)<>'AO' then return base; end if;
 -- Only an exact commune + municipality/province name pair may resolve.
 select count(*) into matches
 from public.afroloc_official_divisions c
 join public.afroloc_official_divisions m on m.code=c.parent_code and m.level=2
 join public.afroloc_official_divisions p on p.code=m.parent_code and p.level=1
 where c.level=3 and lower(btrim(c.name))=lower(btrim(p_neighborhood))
 and (lower(btrim(m.name))=lower(btrim(p_city)) or lower(btrim(p.name))=lower(btrim(p_city)));
 if matches<>1 then return base; end if;
 select p.code as prov,m.code as mun,c.code as com into matched
 from public.afroloc_official_divisions c
 join public.afroloc_official_divisions m on m.code=c.parent_code and m.level=2
 join public.afroloc_official_divisions p on p.code=m.parent_code and p.level=1
 where c.level=3 and lower(btrim(c.name))=lower(btrim(p_neighborhood))
 and (lower(btrim(m.name))=lower(btrim(p_city)) or lower(btrim(p.name))=lower(btrim(p_city)));
 -- Same segment extraction as app.afroloc.ao. DIG denotes digital registration.
 return 'AO-'||left(regexp_replace(matched.prov,'^.*-',''),3)||'-'||
 left(regexp_replace(matched.mun,'^.*-',''),3)||'-'||
 left(regexp_replace(matched.com,'^.*-',''),3)||'-DIG-'||substring(base from 7);
end $$;
revoke all on function public.afroloc_admin_nom(text,text,text,double precision,double precision) from public,anon;
grant execute on function public.afroloc_admin_nom(text,text,text,double precision,double precision) to authenticated,service_role;

create or replace function public.set_afroloc_code() returns trigger language plpgsql set search_path=public as $$
begin
 if tg_op='UPDATE' then
  if (new.latitude,new.longitude,new.country_code,new.city,new.neighborhood,new.afroloc_code)
   is not distinct from (old.latitude,old.longitude,old.country_code,old.city,old.neighborhood,old.afroloc_code) then return new; end if;
 end if;
 if new.latitude is null or new.longitude is null then return new; end if;
 new.afroloc_code:=public.afroloc_admin_nom(coalesce(upper(new.country_code),'AO'),new.city,new.neighborhood,new.latitude,new.longitude);
 return new;
end $$;

create or replace function public.generate_afroloc_code(p_user_id uuid) returns text
language plpgsql stable security definer set search_path=public as $$
declare p record;
begin
 if coalesce(auth.jwt()->>'role','')<>'service_role' and
 (auth.uid() is null or (auth.uid()<>p_user_id and not public.has_role(auth.uid(),'admin'))) then
 raise exception 'Private location access denied' using errcode='42501'; end if;
 select country_code,city,neighborhood,latitude,longitude into p from public.profiles where id=p_user_id;
 return public.afroloc_admin_nom(coalesce(upper(p.country_code),'AO'),p.city,p.neighborhood,p.latitude,p.longitude);
end $$;
