import { PGlite } from '@electric-sql/pglite';
import { readFile } from 'node:fs/promises';
import assert from 'node:assert/strict';
import { test } from 'node:test';
test('admin operations preserve authorization and atomicity', async () => {
 const db = new PGlite();
 try {
 await db.exec(`create role anon; create role authenticated; create schema auth;
 create function auth.uid() returns uuid language sql stable as $$select nullif(current_setting('request.jwt.claim.sub',true),'')::uuid$$;
 create function public.has_role(uuid,text) returns boolean language sql stable as $$select $1='00000000-0000-0000-0000-000000000001'::uuid$$;
 create table posts(id uuid primary key);
 create table discover_topics(id uuid primary key default gen_random_uuid(),name text,slug text unique,display_order integer,post_count integer,is_trending boolean);
 create table post_topics(id uuid primary key default gen_random_uuid(),post_id uuid references posts,topic_id uuid references discover_topics,unique(post_id,topic_id));
 create table topic_suggestions(id uuid primary key,name text,slug text,status text,reviewed_by uuid,reviewed_at timestamptz,rejection_reason text);
 create table live_sessions(id uuid primary key,status text);
 grant usage on schema auth to authenticated,anon;
 grant all on all tables in schema public to authenticated;
 alter table post_topics enable row level security;
 alter table live_sessions enable row level security;
 create policy read_links on post_topics for select using(true);
 insert into posts values('00000000-0000-0000-0000-000000000010');
 insert into live_sessions values('00000000-0000-0000-0000-000000000020','live');
 insert into discover_topics(id,name,slug,display_order) values ('00000000-0000-0000-0000-000000000030','A','a',1),('00000000-0000-0000-0000-000000000031','B','b',2);
 insert into topic_suggestions values('00000000-0000-0000-0000-000000000040','C','c','pending',null,null,null),('00000000-0000-0000-0000-000000000041','A','a','pending',null,null,null);`);
 await db.exec(await readFile(new URL('../supabase/migrations/20261029211014_admin_module_integrity.sql',import.meta.url),'utf8'));
 const id=n=>'00000000-0000-0000-0000-'+String(n).padStart(12,'0');
 const as=async n=>{await db.exec('reset role;set role authenticated');await db.query("select set_config('request.jwt.claim.sub',$1,false)",[id(n)]);};
 const action=(a,target=null,ids=[],reason=null)=>db.query('select admin_topic_action($1,$2,$3,$4)',[a,target,ids,reason]);
 await as(2);
 await assert.rejects(action('assign',id(10),[id(30)]),/Admin required/);
 assert.equal((await db.query('select * from live_sessions')).rows.length,0);
 await assert.rejects(db.query('insert into post_topics(post_id,topic_id) values($1,$2)',[id(10),id(30)]),/row-level security/);
 await as(1);
 assert.equal((await db.query('select * from live_sessions')).rows.length,1);
 await action('assign',id(10),[id(30)]);
 await assert.rejects(action('assign',id(10),[id(99)]),/foreign key/);
 assert.equal((await db.query('select topic_id from post_topics')).rows[0].topic_id,id(30));
 await action('assign',id(10),[id(31)]);
 assert.equal((await db.query('select topic_id from post_topics')).rows[0].topic_id,id(31));
 await action('reorder',null,[id(31),id(30)]);
 await assert.rejects(action('reorder',null,[id(31),id(31)]),/Topics changed/);
 assert.equal((await db.query('select id from discover_topics order by display_order')).rows[0].id,id(31));
 await action('approve',id(40));
 await assert.rejects(action('approve',id(40)),/already reviewed/);
 await assert.rejects(action('approve',id(41)),/unique constraint/);
 assert.equal((await db.query('select status from topic_suggestions where id=$1',[id(41)])).rows[0].status,'pending');
 await action('reject',id(41),[],'Duplicate');
 assert.equal((await db.query('select post_count from admin_topic_counts() where topic_id=$1',[id(31)])).rows[0].post_count,1);
 await action('delete',id(31));
 assert.equal((await db.query('select * from post_topics')).rows.length,0);
 await db.exec('reset role;set role anon');
 await assert.rejects(action('delete',id(30)),/permission denied/);
 } finally {await db.close();}
});
